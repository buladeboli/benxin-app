  function numTxt(v, n) {
    const f = Number(v);
    if (!isFinite(f)) return String(v);
    const d = (n === undefined) ? ((Math.abs(f) < 1 && f !== 0) ? 4 : 3) : n;
    const s = f.toFixed(d);
    if (s.indexOf('.') < 0) return s;
    return s.replace(/0+$/, '').replace(/\.$/, '') || '0';
  }
  /** 出厂默认值（来自 PARAM_DEFS 的 d 字段） */
